package applet;

import javacard.framework.*;
import javacard.security.MessageDigest;

/**
 * Manages the PIN for the rental card, including setting, verifying, and
 * tracking remaining attempts.
 *
 * PIN verification is session-nonce-bound. See README - "Session-bound PIN
 * verification" for the full explanation of why this is necessary.
 */
public class PinManager {

  private OwnerPIN pin;
  private boolean pinSet;
  // Kept separately so we can compute SHA-256(nonce || storedHash) at verify time.
  // OwnerPIN does not expose its stored bytes, so we need our own copy.
  private byte[] storedPinHash;
  // Transient scratch buffer for the nonce-bound hash comparison; cleared on deselect.
  private byte[] computedBuf;
  private MessageDigest sha256;

  /**
   * Constructs a new PinManager. Allocates transient memory for the comparison
   * buffer (cleared on card deselect) and initialises the SHA-256 digest engine.
   */
  public PinManager() {
    pin = new OwnerPIN(AppletConstants.MAX_PIN_TRIES, (byte) AppletConstants.PIN_HASH_LENGTH);
    pinSet = false;
    storedPinHash = new byte[AppletConstants.PIN_HASH_LENGTH];
    computedBuf = JCSystem.makeTransientByteArray(AppletConstants.PIN_HASH_LENGTH, JCSystem.CLEAR_ON_DESELECT);
    sha256 = MessageDigest.getInstance(MessageDigest.ALG_SHA_256, false);
  }

  /**
   * Set the PIN hash. This can only be called once during personalisation.
   * The hash must be exactly {@link AppletConstants#PIN_HASH_LENGTH} bytes
   * (SHA-256 output of the PIN string).
   *
   * @param hash buffer containing the SHA-256 PIN hash
   * @param off  offset in {@code hash} where the hash starts
   * @param len  length of the hash; must equal {@code PIN_HASH_LENGTH}
   */
  public void setPin(byte[] hash, short off, short len) {
    if (len != AppletConstants.PIN_HASH_LENGTH) {
      ISOException.throwIt(ISO7816.SW_WRONG_LENGTH);
    }
    Util.arrayCopy(hash, off, storedPinHash, (short) 0, len);
    pin.update(hash, off, (byte) len);
    pinSet = true;
  }

  /**
   * Check if the PIN has been set.
   *
   * @return true if the PIN has been set during personalisation, false otherwise
   */
  public boolean isPinSet() {
    return pinSet;
  }

  /**
   * Verify a session-nonce-bound PIN hash.
   *
   * The terminal computes SHA-256(nonce || SHA-256(pin)) and sends the result
   * as receivedHash. This method recomputes SHA-256(nonce || storedPinHash)
   * and compares. If they match the PIN is correct and the try counter is reset.
   * On mismatch the try counter is decremented via OwnerPIN; after
   * MAX_PIN_TRIES failures the card locks the PIN.
   *
   * @param nonce        the session nonce generated by this card in INS_GET_NONCE
   * @param nOff         offset of the nonce in its buffer
   * @param nLen         length of the nonce
   * @param receivedHash buffer containing the nonce-bound hash sent by the terminal
   * @param hOff         offset of the hash in receivedHash
   * @param hLen         length of the hash; must equal PIN_HASH_LENGTH
   * @return true if the PIN is correct, never returns false (throws on failure)
   */
  public boolean verify(byte[] nonce, short nOff, short nLen,
      byte[] receivedHash, short hOff, short hLen) {
    if (hLen != AppletConstants.PIN_HASH_LENGTH) {
      ISOException.throwIt(ISO7816.SW_WRONG_LENGTH);
    }
    if (isBlocked()) {
      ISOException.throwIt(AppletConstants.SW_PIN_LOCKED);
      return false;
    }
    sha256.reset();
    sha256.update(nonce, nOff, nLen);
    sha256.doFinal(storedPinHash, (short) 0, AppletConstants.PIN_HASH_LENGTH, computedBuf, (short) 0);

    // Constant-time comparison: always iterate all bytes to avoid timing side-channel.
    byte diff = 0;
    for (short i = 0; i < AppletConstants.PIN_HASH_LENGTH; i++) {
      diff |= (byte) (computedBuf[i] ^ receivedHash[(short) (hOff + i)]);
    }
    boolean match = (diff == 0);

    if (!match) {
      // We do our own nonce-bound comparison instead of calling pin.check() directly,
      // so OwnerPIN never sees the incoming hash. We must still decrement its internal
      // try counter on mismatch — otherwise repeated failed attempts never lock the PIN.
      // Passing computedBuf (our stored hash) guarantees a mismatch without leaking
      // the real expected value via a timing side-channel.
      pin.check(computedBuf, (short) 0, (byte) AppletConstants.PIN_HASH_LENGTH);
      if (isBlocked()) {
        ISOException.throwIt(AppletConstants.SW_PIN_LOCKED);
      }
      ISOException.throwIt(AppletConstants.SW_PIN_INCORRECT);
      return false;
    }
    pin.resetAndUnblock();
    return true;
  }

  private boolean isBlocked() {
    return pin.getTriesRemaining() <= 0;
  }
}
